"""Support ticket triage

Generated by AutoJEV from spec.json. The spec is the source of truth: change it and
re-run `scaffold.py build`, or edit this file and keep the spec in step.

Problem : Decide, for every inbound support message, whether to drop it, fast-track a policy-backed refund, escalate an urgent or angry customer, route it to a department, or hand it to a person.
Shape   : cascade

  state --> Jev (one call, every question at once) --> policy() in plain code --> outcome

Run it:
    python engine.py --demo                 offline, replays samples.json (no key)
    python engine.py --state case.json      live; needs TYPESAFE_API_KEY
    python engine.py --jsonl cases.jsonl    live, one JSON state per line
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from jev_compat import (  # noqa: E402
    Choice, Noul, OfflineClient, Score, MissingKey, canonical, get_client,
)

HERE = Path(__file__).parent

# Only these top-level fields are sent to Jev. Everything else is context rot.
STATE_FIELDS = ['ticket', 'refund_policy']

# ------------------------------------------------------------------ the questions
# One judgment per question. Ask everything up front: extra questions are nearly free.
QUESTIONS = {
    'is_spam': Noul(
        instructions=(
            'The message is spam, automated, or a sales pitch aimed at us rather '
            'than a request from a customer'
        ),
    ),
    'department': Choice(
        instructions='Which team should handle this message',
        criteria={
            'billing': 'Payments, invoices, refunds, subscriptions',
            'technical': 'Bugs, outages, integrations, errors',
            'sales': 'Pricing, plans, upgrades, new accounts',
            'account': 'Login, permissions, security, profile changes',
            'other': 'None of the above, or cannot be determined',
        },
    ),
    'frustration': Score(
        instructions='How frustrated the customer appears',
        criteria=[
            'Calm, just stating facts',
            'Frustrated but civil',
            'Very angry, strong language',
        ],
    ),
    'urgency': Score(
        instructions='How urgently the customer needs a resolution',
        criteria=[
            'No time pressure',
            'Wants an answer soon',
            'Blocked right now and cannot work',
        ],
    ),
    'refund_requested': Noul(
        instructions='The customer explicitly asks for a refund or credit',
    ),
    'policy_supports': Noul(
        instructions='The refund_policy in the state covers the situation the customer describes',
    ),
}

# ------------------------------------------------------------------ the bars
# One threshold per action, scaled to what being wrong costs. Not one global number.
SPAM_BAR = 0.85  # dropping a real customer is the costly error, so the bar is high
DEPT_FLOOR = 0.7  # a mis-routed ticket costs a hop, not a customer; below this a person decides
REFUND_BAR = 0.8  # only fast-track when the ask is explicit
POLICY_BAR = 0.85  # the refunds desk still issues the money, but a wrong pre-check wastes their time
PRIORITY_BAR = 0.7  # cheap to escalate; erring high only reorders the queue

# ---------------------------------------------- composites (arithmetic lives here)
# Weights are code: they have a diff, a reviewer, a test. Never ask Jev to rate 1-10.
COMPOSITES = {
    'priority': {
        'frustration': 0.5,
        'urgency': 0.5,
    },
}

OUTCOMES = {
    'drop': {'kind': 'block', 'description': 'Discard: spam or automated mail'},
    'fast_track_refund': {'kind': 'auto', 'description': (
            'Refunds desk, flagged as pre-checked against policy (a person still '
            'issues the money)'
        )},
    'priority_queue': {'kind': 'auto', 'description': 'Front of the queue for the best-matching department'},
    'route_to_department': {'kind': 'auto', 'description': 'Normal queue for the chosen department'},
    'human_review': {'kind': 'review', 'description': 'Triage lead decides: Jev was not sure enough'},
}


def trim(state: dict) -> dict:
    """Send Jev only the fields the questions need."""
    if not STATE_FIELDS or not isinstance(state, dict):
        return state
    return {k: state[k] for k in STATE_FIELDS if k in state}


def path(state, dotted: str):
    """state['a']['b'] by 'a.b'; None when absent."""
    cur = state
    for part in dotted.split("."):
        if isinstance(cur, dict) and part in cur:
            cur = cur[part]
        else:
            return None
    return cur


def num(state, dotted: str) -> float:
    """Like path(), but a number; NaN when absent/non-numeric so every comparison is False."""
    value = path(state, dotted)
    return float(value) if isinstance(value, (int, float)) and not isinstance(value, bool) else float("nan")


def compute_composites(a) -> dict:
    """Weighted sums of Score answers, each normalised to 0-1 by its top level."""
    out = {}
    for name, weights in COMPOSITES.items():
        out[name] = sum(w * a[q].score / (len(QUESTIONS[q].criteria) - 1) for q, w in weights.items())
    return out


def policy(a, composite: dict, state: dict) -> dict:
    """Ordered rules, first match wins. Plain code: read it, diff it, test it.

    `a` = Jev's answers, `composite` = weighted scores, `state` = the full input, so hard
    limits and arithmetic can be checked here, in code, not asked of the model.
    """
    # drop_spam: very likely not a customer
    if a['is_spam'].noul > SPAM_BAR:
        return {'outcome': 'drop', 'rule': 'drop_spam', 'why': 'very likely not a customer'}
    # refund_fast_track: explicit refund ask, policy covers it, and billing is clearly the owner
    if a['refund_requested'].noul > REFUND_BAR and a['policy_supports'].noul > POLICY_BAR and a['department'].choice == 'billing' and a['department'].confidence >= DEPT_FLOOR:
        return {'outcome': 'fast_track_refund', 'rule': 'refund_fast_track', 'why': 'explicit refund ask, policy covers it, and billing is clearly the owner'}
    # escalate_priority: angry and/or blocked customers jump the queue
    if composite['priority'] > PRIORITY_BAR:
        return {'outcome': 'priority_queue', 'rule': 'escalate_priority', 'why': 'angry and/or blocked customers jump the queue'}
    # route: Jev is sure enough about the owner
    if a['department'].confidence >= DEPT_FLOOR and a['department'].choice != 'other':
        return {'outcome': 'route_to_department', 'rule': 'route', 'why': 'Jev is sure enough about the owner'}
    return {'outcome': 'human_review', 'rule': 'default', 'why': "no rule was confident enough — say so, don't guess"}


def summarize(a) -> dict:
    """The answers, as plain data you can log (this is the raw material for calibration)."""
    out = {}
    for name, ans in a.items():
        if ans.type == "noul":
            out[name] = {"noul": round(ans.noul, 3)}
        elif ans.type == "choice":
            out[name] = {"choice": ans.choice, "confidence": round(ans.confidence, 3)}
        else:
            out[name] = {"score": round(ans.score, 3), "confidence": round(ans.confidence, 3)}
    return out


def decide(state: dict, client=None) -> dict:
    """One Jev call -> one outcome. `client` defaults to the live, version-pinned client."""
    client = client or get_client()
    started = time.perf_counter()
    response = client.system_one(state=trim(state), questions=QUESTIONS)
    a = response.answers
    composite = compute_composites(a)
    result = policy(a, composite, state)
    result.update(
        composite={k: round(v, 3) for k, v in composite.items()},
        answers=summarize(a),
        model=response.model,
        latency_ms=round((time.perf_counter() - started) * 1000, 1),
    )
    return result


def offline_client() -> OfflineClient:
    samples = json.loads((HERE / "samples.json").read_text())
    return OfflineClient({canonical(trim(s["state"])): s["fixture"] for s in samples})


def main() -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    ap.add_argument("--demo", "--offline", dest="demo", action="store_true",
                    help="replay samples.json with canned answers (tests the policy, not Jev)")
    ap.add_argument("--state", help="path to a JSON file holding one state")
    ap.add_argument("--jsonl", help="path to a file with one JSON state per line")
    args = ap.parse_args()

    try:
        if args.demo:
            client = offline_client()
            for s in json.loads((HERE / "samples.json").read_text()):
                r = decide(s["state"], client)
                flag = "ok " if r["outcome"] == s.get("expect") else "!! "
                print(f"{flag}{s['id']:<22} -> {r['outcome']:<18} via {r['rule']}")
            print("\n(offline: canned answers. This exercises the rules, not Jev's judgment.)")
        elif args.state:
            print(json.dumps(decide(json.loads(Path(args.state).read_text())), indent=2))
        elif args.jsonl:
            client = get_client()
            for line in Path(args.jsonl).read_text().splitlines():
                if line.strip():
                    print(json.dumps(decide(json.loads(line), client)))
        else:
            ap.print_help()
    except MissingKey as exc:
        print(f"{exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
